/** 코드에 실제로 쓰인 키워드 집합 (주석/문자열 제외) */
function keywordsIn(code: string): Set<string> {
  try {
    return new Set(tokenize(code).filter((t) => t.type === 'keyword').map((t) => t.value))
  } catch {
    return new Set()
  }
}

/** 코드에 해당 기호가 실제로 쓰였는지 (주석/문자열 제외) */
function hasOp(code: string, op: string): boolean {
  try {
    return tokenize(code).some((t) => t.type === 'op' && t.value === op)
  } catch {
    return false
  }
}

/** 변수에 값을 넣는 문장이 있는지 */
function hasAssignment(code: string): boolean {
  try {
    const ts = tokenize(code)
    return ts.some((t, i) => t.type === 'ident' && ts[i + 1]?.type === 'op' && ts[i + 1].value === '=')
  } catch {
    return false
  }
}

/** 코드에 그 키워드가 몇 번 쓰였는지 (주석/문자열 제외) */
function countKeyword(code: string, kw: string): number {
  try {
    return tokenize(code).filter((t) => t.type === 'keyword' && t.value === kw).length
  } catch {
    return 0
  }
}

/** 코드에서 그 이름의 함수를 몇 번 불렀는지 */
function countCalls(code: string, name: string): number {
  try {
    const ts = tokenize(code)
    return ts.filter((t, i) => t.type === 'ident' && t.value === name
      && ts[i + 1]?.type === 'op' && ts[i + 1].value === '(').length
  } catch {
    return 0
  }
}

